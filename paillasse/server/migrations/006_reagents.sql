-- Produits chimiques et réactifs : masse molaire et concentrations d'usage, pour les calculs de paillasse.
-- Base initiale reprise de LabHelper v3 (153 produits, created_by NULL), avec quelques corrections :
-- glycine 75,07 g/mol, SAM 398,44 g/mol, orthovanadate 183,91 g/mol ; polymyxine B et G418 décrits comme les
-- sels (sulfate, disulfate) auxquels correspondent leurs masses molaires.
--
-- Un calcul inséré dans une entrée du cahier garde sa propre copie de la masse molaire utilisée :
-- corriger un produit ici ne change jamais une entrée existante. On archive, on ne supprime pas.

CREATE TABLE reagents (
  id           uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name         text NOT NULL,
  formula      text NOT NULL DEFAULT '',
  mw           double precision CHECK (mw IS NULL OR mw > 0),   -- g/mol ; NULL si sans objet (extrait, mélange)
  category     text NOT NULL DEFAULT '',
  stock_conc   text NOT NULL DEFAULT '',                        -- solution mère usuelle (texte libre)
  working_conc text NOT NULL DEFAULT '',                        -- concentration d'usage
  notes        text NOT NULL DEFAULT '',
  archived     boolean NOT NULL DEFAULT false,
  created_by   uuid REFERENCES users(id),                       -- NULL : base initiale
  updated_by   uuid REFERENCES users(id),
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX reagents_name_idx ON reagents (lower(name)) WHERE NOT archived;

CREATE TRIGGER reagents_no_delete BEFORE DELETE ON reagents
  FOR EACH ROW EXECUTE FUNCTION paillasse_forbid_delete();

